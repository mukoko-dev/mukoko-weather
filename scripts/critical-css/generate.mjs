// Make the critical subset of the stylesheet (issue #551):
//
//   node scripts/critical-css/generate.mjs          # write the subset
//   node scripts/critical-css/generate.mjs --check  # fail when it is out of date
//
// The stylesheet is src/app/globals.css as the build makes it (`compile.mjs`);
// the vocabulary is what `record.mjs` saw in the first screen's real DOM; the
// rule is `select.mjs`. The output, src/lib/critical-css/critical.generated.json,
// is committed, so a build needs no browser; the test in
// src/lib/critical-css/critical-css.test.ts runs the same three steps and fails
// when this file is not what they make, which is how a change to a colour, a
// spacing token or a utility reaches the first paint and not only the second.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compileStylesheet, TARGETS } from "./compile.mjs";
import { selectCritical } from "./select.mjs";
import { VOCABULARY_PATH } from "./vocabulary.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const GENERATED_PATH = join(
  ROOT,
  "src",
  "lib",
  "critical-css",
  "critical.generated.json",
);

/**
 * The text of critical.generated.json for a stylesheet. JSON, not a module: it
 * is data (a copy of rules whose source is already checked), and the repo's
 * scans of source for type sizes and chart tokens read .ts, .tsx and .css only.
 * `critical` says what it is, since JSON cannot carry a comment.
 */
export function generatedSource(css) {
  return `${JSON.stringify(
    {
      note: "GENERATED by scripts/critical-css/generate.mjs. Do not edit by hand. The rules of src/app/globals.css that the first screen of / and of a place page uses (vocabulary.json is the DOM they build): issue #551. Public, static CSS; nothing about a visitor is in it.",
      css,
    },
    null,
    2,
  )}\n`;
}

export async function makeCritical() {
  const vocabulary = JSON.parse(await readFile(VOCABULARY_PATH, "utf8"));
  const full = await compileStylesheet();
  const critical = selectCritical(full, vocabulary, { targets: TARGETS });
  return { full, ...critical, source: generatedSource(critical.css) };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes("--check");
  const made = await makeCritical();
  const gz = (await import("node:zlib")).gzipSync(made.css).length;
  console.log(
    `stylesheet ${made.full.length} bytes; critical ${made.css.length} bytes (${gz} gzipped), ${made.rules.kept} rules kept, ${made.rules.dropped} dropped`,
  );
  if (check) {
    const current = await readFile(GENERATED_PATH, "utf8").catch(() => "");
    if (current !== made.source) {
      console.error(
        "critical.generated.json is out of date: run `node scripts/critical-css/generate.mjs`",
      );
      process.exit(1);
    }
    console.log("critical.generated.json is up to date");
  } else {
    await writeFile(GENERATED_PATH, made.source);
    console.log(`wrote ${GENERATED_PATH}`);
  }
}
